// Single schema source for the inactive Phase 2A codecs. No Firebase access.
import {mkdirSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve, dirname} from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const text = (max = 200, min = 0) => ({type: 'string', max, min});
const id = {...text(160, 1), pattern: '^[A-Za-z0-9_-]+$'};
const integer = (min = 0, max = 9007199254740991) => ({type: 'integer', min, max});
const money = {type: 'number', min: 0, max: 1000000000000, nullable: true};
const enumeration = (...values) => ({type: 'enum', values});
const object = (fields, required = Object.keys(fields)) => ({type: 'object', fields, required});
const array = (items, max, unique = false) => ({type: 'array', items, max, unique});
const nullable = s => ({...s, nullable: true});
const names = array(text(160, 1), 50, true);
const eventFields = {
  eventType: text(120, 1), eventDate: {...text(10, 10), format: 'date'},
  eventTime: {...text(5, 5), format: 'time'}, eventEndTime: {...text(5, 5), format: 'time'},
  guestCount: integer(1, 10000), eventLocation: text(180), eventAddress: text(500), specialRequest: text(1000),
};
const pricing = nullable(object({currency: enumeration('PHP'), pricingModel: nullable(enumeration('per_pax', 'per_bundle')), displayedServicePrice: money}));
const food = object({groupId: {...id, max: 64}, optionIds: {...array({...id, max: 64}, 50, true), min: 1}});
const service = object({id, providerId: id, providerName: text(200, 1), name: text(200, 1), category: nullable(text(120)), price: money, source: enumeration('catering_provider', 'feasta_addon_provider')}, ['id','providerId','providerName','name','category','price']);
const addon = object({serviceId: id, expectedRevision: integer(1), addonId: id, providerId: id, source: enumeration('catering_provider','feasta_addon_provider'), name: text(200, 1), providerBusinessName: text(200, 1), providerType: text(120), category: text(120), price: money}, ['addonId','providerId','source','name','providerBusinessName','providerType','category','price']);
const configFields = {
  event: object(eventFields), sharedContractVersion: nullable(enumeration(2)), expectedPackageRevision: nullable(integer(1)),
  serviceTier: nullable(enumeration('drop_off','buffet_setup','full_service')), packageThemeId: nullable(id),
  themeInspiration: object({notes: text(1000), referenceSetupId: nullable(id)}),
  themeChoice: nullable(enumeration('custom','none','package')), customTheme: text(10000),
  foodChoiceSelections: array(food, 10), selectedFoods: names, selectedDecorations: names, selectedFurniture: names,
  selectedEventServices: array(service, 30), selectedAddOns: array(addon, 20), specialRequest: text(1000),
  willArrangeOwnAddOns: {type: 'boolean'}, customerArrangedAddOnsNote: text(1000), estimatedTotal: money, pricingContext: pricing,
};
const configuration = nullable(object(configFields, ['event','selectedFoods','selectedDecorations','selectedFurniture','willArrangeOwnAddOns','customerArrangedAddOnsNote','estimatedTotal']));
const menu = nullable(object({key: text(500, 1), servingOptionName: text(200, 1), servingDescription: text(1000), servingMinimumGuests: integer(1,1000000), servingMaximumGuests: integer(1,1000000)}, ['key','servingOptionName','servingDescription','servingMinimumGuests','servingMaximumGuests']));
const entry = object({
  kind: enumeration('catering_package','custom_menu','marketplace_service'), providerId: id, selectionId: id,
  variantId: nullable(id), identity: text(500,1), providerName: text(200,1), name: text(200,1), estimatedPrice: money,
  imageUrl: nullable(text(2048)), expectedRevision: nullable(integer(1)), configuration,
  href: nullable(text(1000)), menu,
});
const schema = object({
  version: enumeration(1), ownerUid: {...id,max:128}, revision: integer(), currency: enumeration('PHP'),
  entries: array(entry,24), schedule: nullable(object(eventFields, ['eventDate','eventTime'])),
  migration: object({version: enumeration(1), completed: enumeration(true)}),
});
for (const folder of ['contracts/customer-event-list','functions/src/customer-event-lists','apps/customer_mobile/lib/shared/models']) mkdirSync(resolve(root,folder),{recursive:true});
const json = JSON.stringify(schema,null,2);
writeFileSync(resolve(root,'contracts/customer-event-list/schema.json'),json+'\n');
writeFileSync(resolve(root,'functions/src/customer-event-lists/schema.ts'),'// Generated by scripts/generate-customer-event-list-schema.mjs.\nexport const eventListSchema = '+json+' as const;\n');
writeFileSync(resolve(root,'apps/customer_mobile/lib/shared/models/customer_event_list_cloud_schema.dart'),"// Generated by scripts/generate-customer-event-list-schema.mjs.\n// JSON is kept as a string so both codecs consume identical schema semantics.\nconst customerEventListCloudSchemaJson = r'''"+json+"''';\n");
